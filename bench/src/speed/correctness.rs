#![allow(dead_code)]

// Correctness checking utilities for QMDB benchmark.
//
// This module is only compiled when the `qmdb_bench_correctness` feature
// is enabled. It provides a lightweight "bitmap reference model" that
// tracks state in the integer key space instead of storing all key/value
// pairs in memory.

#[cfg(feature = "qmdb_bench_correctness")]
use byteorder::{BigEndian, ByteOrder};
#[cfg(feature = "qmdb_bench_correctness")]
use parking_lot::RwLock;
#[cfg(feature = "qmdb_bench_correctness")]
use qmdb::test_helper::SimpleTask;
#[cfg(feature = "qmdb_bench_correctness")]
use qmdb_common::{
    def::{OP_CREATE, OP_DELETE, OP_WRITE},
    task::task::Task,
};

#[cfg(feature = "qmdb_bench_correctness")]
fn bitset_len(bits: u64) -> usize {
    ((bits + 7) / 8) as usize
}

#[cfg(feature = "qmdb_bench_correctness")]
fn bit_get(bits: &[u8], idx: u64) -> bool {
    let byte = (idx / 8) as usize;
    let mask = 1u8 << (idx % 8);
    if byte >= bits.len() {
        return false;
    }
    bits[byte] & mask != 0
}

#[cfg(feature = "qmdb_bench_correctness")]
fn bit_set(bits: &mut [u8], idx: u64, value: bool) {
    let byte = (idx / 8) as usize;
    let mask = 1u8 << (idx % 8);
    if byte >= bits.len() {
        return;
    }
    if value {
        bits[byte] |= mask;
    } else {
        bits[byte] &= !mask;
    }
}

/// Lightweight bitmap-based reference model.
///
/// Tracks:
/// - For the stable range [0, entry_count_wo_del): whether a key has been updated at least once.
/// - For the deletable range [entry_count_wo_del, entry_count_wo_del + delete_count):
///   whether a key currently exists.
#[cfg(feature = "qmdb_bench_correctness")]
pub struct BitmapModel {
    /// Total configured entries.
    pub entry_count: u64,
    /// Entries that are never deleted (stable range size).
    pub entry_count_wo_del: u64,
    /// Number of entries in the deletable range.
    pub delete_count: u64,
    /// Bitmap for "has been updated" in stable range.
    pub updated: Vec<u8>,
    /// Bitmap for "currently exists" in deletable range.
    pub exists: Vec<u8>,
}

#[cfg(feature = "qmdb_bench_correctness")]
impl BitmapModel {
    pub fn new(entry_count: u64, entry_count_wo_del: u64) -> Self {
        let delete_count = entry_count.saturating_sub(entry_count_wo_del);
        let updated_len = bitset_len(entry_count_wo_del);
        let exists_len = bitset_len(delete_count);
        Self {
            entry_count,
            entry_count_wo_del,
            delete_count,
            updated: vec![0u8; updated_len],
            exists: vec![0u8; exists_len],
        }
    }

    /// Apply all operations in a block to the bitmap model.
    ///
    /// This walks over all `ChangeSet`s in the given `task_list` and updates
    /// the bitmaps based on the operation type and decoded integer `num`
    /// embedded in the key bytes.
    pub fn apply_block(&mut self, task_list: &[RwLock<Option<SimpleTask>>]) {
        for item in task_list.iter() {
            let guard = item.read();
            let Some(task) = guard.as_ref() else {
                continue;
            };
            let change_sets = task.get_change_sets();
            for cset in change_sets.iter() {
                cset.for_each_op(|op_type, _, _kh, key, _value, _, _rec| {
                    // Keys generated by `TestGenV2::fill_kv` store the logical
                    // integer `num` in bytes [12..20].
                    if key.len() < 20 {
                        return;
                    }
                    let num = BigEndian::read_u64(&key[12..20]);

                    if num < self.entry_count_wo_del {
                        // Stable range: we deliberately do **not** track OP_CREATE here.
                        // Design invariant:
                        // - Round 0 fully populates [0, entry_count_wo_del) with OP_CREATE.
                        // - This range is never deleted afterwards.
                        // Therefore the only interesting state transition for correctness
                        // checking is: "has this key been updated at least once in round 1".
                        if op_type == OP_WRITE {
                            bit_set(&mut self.updated, num, true);
                        }
                    } else {
                        // Deletable range: shift index to [0, delete_count).
                        let idx = num.saturating_sub(self.entry_count_wo_del);
                        if idx >= self.delete_count {
                            // High-numbered "new" entries are not tracked by the bitmap model.
                            return;
                        }
                        match op_type {
                            OP_CREATE => bit_set(&mut self.exists, idx, true),
                            OP_DELETE => bit_set(&mut self.exists, idx, false),
                            _ => {}
                        }
                    }
                });
            }
        }
    }

    /// Query helpers for future sampling/checking logic.
    ///
    /// Note: we intentionally do **not** track OP_CREATE in the stable
    /// range [0, entry_count_wo_del). The design guarantees that this
    /// range is fully populated during round 0 and never deleted, so
    /// the only interesting state transition there is "has this key
    /// been updated at least once in round 1".
    pub fn is_updated(&self, num: u64) -> bool {
        if num >= self.entry_count_wo_del {
            return false;
        }
        bit_get(&self.updated, num)
    }

    /// Returns whether a key is both *tracked by the bitmap model* and
    /// currently considered to exist.
    ///
    /// Semantics:
    /// - Stable range [0, entry_count_wo_del): always returns true, because
    ///   these keys are guaranteed to exist after round 0 and are never
    ///   deleted by the workload.
    /// - Deletable range [entry_count_wo_del, entry_count_wo_del + delete_count):
    ///   returns the corresponding bit from the `exists` bitmap.
    /// - Higher ranges (e.g. "new" entries created in round 1 and beyond):
    ///   return false, meaning "not tracked by this model" rather than
    ///   "must not exist in the database".
    pub fn is_tracked_and_exists(&self, num: u64) -> bool {
        if num < self.entry_count_wo_del {
            return true;
        }
        let idx = num.saturating_sub(self.entry_count_wo_del);
        if idx >= self.delete_count {
            // Outside of deletable range; bitmap does not track these keys.
            return false;
        }
        bit_get(&self.exists, idx)
    }

    /// Returns the expected existence state for a logical key number.
    ///
    /// Semantics:
    /// - Stable range [0, entry_count_wo_del): always returns Some(true), since
    ///   these keys are fully populated in round 0 and never deleted.
    /// - Deletable range [entry_count_wo_del, entry_count_wo_del + delete_count):
    ///   returns Some(true) if the key is currently expected to exist, or
    ///   Some(false) if it is expected to have been deleted.
    /// - Higher ranges (new entries beyond the tracked space): returns None,
    ///   meaning "not tracked by this model".
    pub fn existence_state(&self, num: u64) -> Option<bool> {
        if num < self.entry_count_wo_del {
            return Some(true);
        }

        let idx = num.saturating_sub(self.entry_count_wo_del);
        if idx >= self.delete_count {
            return None;
        }

        Some(bit_get(&self.exists, idx))
    }
}

/// Build a key and expected value for a given logical `num` and expected round.
///
/// This mirrors the logic in `TestGenV2::fill_kv`, but takes `expected_round`
/// as an explicit parameter so that correctness checking does not depend on
/// the internal `cur_round` state of the workload generator.
#[cfg(feature = "qmdb_bench_correctness")]
pub fn build_key_and_expected_value(num: u64, expected_round: u32) -> ([u8; 52], [u8; 32]) {
    let mut k = [0u8; 32 + 20];
    let mut v = [0u8; 32];

    // Encode `num` into key bytes [12..20], exactly as in `fill_kv`.
    BigEndian::write_u64(&mut k[12..20], num);
    let hash = qmdb_common::entryfile::entry::entry_key_hash(&k[12..20]);
    k[20..20 + 32].copy_from_slice(&hash[..]);
    for i in 0..12 {
        k[i] = k[20 + i] ^ k[32 + i];
    }

    // Compute final key-hash and expected value.
    let kh = qmdb_common::entryfile::entry::entry_key_hash(&k[..]);
    BigEndian::write_u32(&mut v[..4], expected_round);
    v[4..].copy_from_slice(&kh[4..]);

    (k, v)
}
